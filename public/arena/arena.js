// THE ARENA. Hosts a sandbox — someone else's code — behind an iframe, with a task
// Alexandria generated. The world declares WHERE it sits, so this is not a region of the
// chrome; it is the set of things a tenant may never renegotiate, wherever it is mounted.
// Design and the invariants: `Alexandria - Design`, "The arena".
//
// The projector and the arena are the main surface's two tenants with DIFFERENT boundaries:
// a world is a shadow root because it ships no JavaScript, an engine is an iframe because
// it does. That is why this is a separate module and not a branch inside the projector.
//
// It deliberately imports nothing from `public/app.js`. An engine mount must work with no
// world on screen at all — see `bench.html`, which runs the whole arena with no projector,
// no model and no quota.

import { MSG, SANDBOX_FLAGS, PROTOCOL, entryUrl, shapeResult } from '/src/engine.js';

// NOTHING SPINS. An engine that is not warm is replaced, not waited for, so the handshake
// has a deadline and missing it is a degrade rather than a wait. Generous for a local
// package on a cold cache, and short enough that a student never watches a dead frame.
export const READY_DEADLINE_MS = 3000;

const el = (tag, cls, text) => {
  const n = document.createElement(tag);
  if (cls) n.className = cls;
  if (text != null) n.textContent = text;
  return n;
};

// Provenance sits in the bar for the LIFE of the mount, not behind a disclosure. This is
// third-party code running inside a student's session; the requirement is in
// `Alexandria - Interactives` and it is the reason review status is rendered even when it
// is the boring value.
function provenance(engine) {
  const wrap = el('div', 'arena-prov');
  wrap.append(el('span', 'arena-prov-name', `${engine.name} ${engine.version}`));
  wrap.append(el('span', 'arena-prov-by', `by ${engine.author}`));
  const review = el('span', `arena-review arena-review--${engine.review}`, engine.review);
  wrap.append(review);
  return wrap;
}

/**
 * Mount an engine. Returns a handle; the caller owns teardown.
 *
 * Two outcomes, not three. A mount that ends normally produces a ledger payload either
 * way — `result.completed === false` is what tells the ledger to OWE the item — and a
 * degrade is genuinely different, because it substitutes a micro set and never reaches the
 * ledger at all. An earlier draft had a third `onSkip`, which carried the same payload as
 * `onResult` and made two names for one thing.
 */
export function mountArena(host, {
  engine,
  task,                  // { kind, params, sentence } — `sentence` is the chrome's, never the engine's
  banked = false,
  onResult = () => {},
  onDegrade = () => {},
}) {
  const root = el('div', 'arena');
  const bar = el('div', 'arena-bar');

  // THE CHROME STATES THE TASK. Task parameters are generated by Alexandria and an engine
  // declares only a task space, so the sentence cannot belong to the tenant. The engine is
  // sent `params` and never `sentence`, which is what makes that structural rather than a
  // convention someone remembers.
  const stated = el('div', 'arena-task');
  stated.append(el('span', 'arena-task-label', 'Task'));
  stated.append(el('p', 'arena-task-sentence', task.sentence));

  // The exit control is always present and never blocked. Two states, same position and
  // same size — only the weight changes, so nothing moves when the bank lands.
  const exit = el('button', 'arena-exit');
  const paint = () => {
    exit.textContent = banked ? 'Continue' : 'Skip';
    exit.classList.toggle('arena-exit--banked', banked);
  };
  paint();

  bar.append(stated, provenance(engine), exit);

  const stage = el('div', 'arena-stage');
  const frame = document.createElement('iframe');
  frame.className = 'arena-frame';
  frame.setAttribute('sandbox', SANDBOX_FLAGS);   // see src/engine.js — no allow-same-origin
  frame.setAttribute('title', `${engine.name}, an interactive`);
  frame.src = entryUrl(engine);
  stage.append(frame);

  const notice = el('p', 'arena-notice');          // the degrade's one quiet line
  notice.hidden = true;

  root.append(bar, stage, notice);
  host.append(root);

  let started = 0;        // when the engine became usable, not when the frame was created
  let settled = false;    // a result or a degrade has already happened
  // The last partial the engine pushed. This is what a student who leaves mid-task is
  // carrying, and it is the only reason their misconception survives the exit.
  let latest = {};
  let deadline = setTimeout(() => degrade('engine did not report ready within ' + READY_DEADLINE_MS + 'ms'), READY_DEADLINE_MS);

  const elapsed = () => (started ? performance.now() - started : 0);

  function degrade(reason) {
    if (settled) return;
    settled = true;
    clearTimeout(deadline);
    // A substitution, not a fault: `--warn`, one muted line, no error panel and no
    // dismissal. The named reason still exists for the log; the student is told what is
    // happening rather than what went wrong.
    notice.textContent = 'This simulation is still downloading. Here is something else meanwhile.';
    notice.hidden = false;
    stage.hidden = true;
    console.info(`[arena] degrade: ${reason}`);
    onDegrade(reason);
  }

  function finish(raw, completed) {
    if (settled) return;
    settled = true;
    clearTimeout(deadline);
    onResult(shapeResult({ engine, raw, timeOnTaskMs: elapsed(), completed }));
  }

  // Always available, never blocked, and it is the ONLY way out of an unscored engine —
  // that kind has no completion event to wait for. Leaving a scored engine mid-task is
  // allowed and costs nothing; it shows up downstream as `completed: false`.
  exit.addEventListener('click', () => finish(latest, false));

  function onMessage(ev) {
    // THE ONLY IDENTITY CHECK AVAILABLE. The frame has an opaque origin, so `ev.origin` is
    // the string "null" for every message it sends and comparing it proves nothing. The
    // window reference does — no other document can forge it.
    if (ev.source !== frame.contentWindow) return;
    const msg = ev.data;
    if (!msg || typeof msg !== 'object') return;

    if (msg.type === MSG.ready) {
      if (started) return;                       // a second ready is noise, not a restart
      clearTimeout(deadline);
      started = performance.now();
      frame.contentWindow.postMessage(
        { type: MSG.task, version: PROTOCOL, kind: task.kind, params: task.params },
        '*',                                     // opaque origin cannot be named; the frame
      );                                         // reference above is what scopes this
      return;
    }
    // A partial, kept rather than acted on. It never changes the screen — the arena draws
    // what happened only at the end — so an engine cannot use it to redraw the chrome.
    if (msg.type === MSG.state) { latest = msg.result ?? latest; return; }
    if (msg.type === MSG.complete) return finish(msg.result ?? latest, true);
    if (msg.type === MSG.error) return degrade(`engine reported: ${String(msg.message).slice(0, 200)}`);
  }

  window.addEventListener('message', onMessage);

  return {
    el: root,
    // How the bank becomes visible, and the ONLY way it does. This deliberately breaks
    // "only the student's action changes the screen" — narrowed on 26 Aug so the rule
    // covers material rather than affordances, because without it the student is guessing
    // whether leaving costs a wait.
    setBanked(v) { banked = v; paint(); },
    destroy() {
      settled = true;
      clearTimeout(deadline);
      window.removeEventListener('message', onMessage);
      root.remove();
    },
  };
}
